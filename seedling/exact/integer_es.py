"""Evolution strategies whose updates are exact integers.

Same ask/tell loop as seedling.es.ES, with two changes:
  - noise is +-1 per element (Rademacher), generated by Philox in C from the seed;
  - tell() turns the scores into one integer coefficient per seed and applies them to an
    int32 FixedPointState. The StepRecord it returns replays the step bit for bit.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np
import torch

from seedling import _c
from seedling.es.es import FitnessShaper, centered_ranks, step_seeds
from seedling.exact.record import StepRecord
from seedling.exact.state import INT32, FixedPointState


def rademacher_noise(seed: int, n: int) -> torch.Tensor:
    """+-1 noise as float32, rebuilt from its seed by Philox (the same bits on every machine)."""
    return torch.from_numpy(_c.rademacher_i8(seed, n).astype(np.float32))


def integer_coefficients(
    f_plus: np.ndarray,
    f_minus: np.ndarray,
    lr: float,
    sigma: float,
    frac_bits: int,
    shaper: FitnessShaper = centered_ranks,
) -> list[int]:
    """q_i = round(lr * (F+_i - F-_i) / (2 N sigma) * 2**frac_bits), with shaped scores."""
    n = len(f_plus)
    shaped = shaper(np.concatenate([np.asarray(f_plus), np.asarray(f_minus)]))
    weights = (shaped[:n] - shaped[n:]) * lr / (2 * n * sigma) * 2.0**frac_bits
    q = np.rint(weights)
    if np.abs(q).max(initial=0) > INT32.max:
        raise OverflowError("coefficient does not fit int32: lower lr or frac_bits")
    return [int(v) for v in q]


class IntegerES:
    def __init__(
        self,
        state: FixedPointState,
        pop: int = 32,
        sigma: float = 0.05,
        lr: float = 0.05,
        seed: int = 0,
        shaper: FitnessShaper = centered_ranks,
    ):
        self.state = state
        self.pop = pop
        self.sigma = sigma
        self.lr = lr
        self.seed = seed
        self.shaper = shaper
        self.step = 0

    @property
    def theta(self) -> torch.Tensor:
        return self.state.to_float()

    def ask(self) -> list[int]:
        return step_seeds(self.seed, self.step, self.pop)

    def tell(self, seeds: Sequence[int], f_plus: np.ndarray, f_minus: np.ndarray) -> StepRecord:
        coefs = integer_coefficients(f_plus, f_minus, self.lr, self.sigma, self.state.frac_bits, self.shaper)
        record = StepRecord(self.step, tuple(seeds), tuple(coefs))
        self.state.apply(record)
        self.step += 1
        return record


def replay(state: FixedPointState, records: Sequence[StepRecord]) -> FixedPointState:
    """Apply recorded steps, in order, to a copy of the starting state."""
    result = state.copy()
    for record in records:
        result.apply(record)
    return result
